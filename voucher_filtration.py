price_df['Product_ID']    = price_df.get('ProductId', '')
price_df['Status_Active'] = 'active'
price_df['Quantity']      = price_df.get('Quantity', 0)

# Drop price columns from price file — will use zeCOM AU/AV instead
price_df.drop(columns=[c for c in ['Price','Sale_Price_raw','Special_Price'] if c in price_df.columns], inplace=True)
print(f"  ✓ {len(price_df):,} SKUs loaded")


# ============================================================
# STEP 2: Map ALU_NO via Content File
# ============================================================
print("\n▶ STEP 2: Mapping ALU_NO via Content file...")
if not os.path.exists(CONTENT_FILE):
    print(f"  ERROR: File not found → {CONTENT_FILE}"); sys.exit(1)

content_df = pd.read_excel(CONTENT_FILE, sheet_name='content')[['Color_No', 'EAN']].copy()
content_df['EAN'] = content_df['EAN'].astype(str).str.strip()

def normalise_ean(v):
    return str(v).strip().split('.')[0].strip()

content_df['EAN_norm'] = content_df['EAN'].apply(normalise_ean)
content_df = content_df.drop_duplicates(subset='EAN_norm')

price_df['EAN_norm'] = price_df['SellerSKU'].apply(normalise_ean)
price_df = price_df.merge(content_df[['EAN_norm', 'Color_No']], on='EAN_norm', how='left')
price_df.rename(columns={'Color_No': 'ALU_NO'}, inplace=True)

matched = price_df['ALU_NO'].notna().sum()
print(f"  ✓ {matched:,} / {len(price_df):,} SKUs matched to ALU_NO")


# ============================================================
# STEP 3: Load zeCOM Tracking File
# ============================================================
print("\n▶ STEP 3: Loading zeCOM Tracking file (sheet: MY)...")
if not os.path.exists(ZECOM_FILE):
    print(f"  ERROR: File not found → {ZECOM_FILE}"); sys.exit(1)

wb_z = openpyxl.load_workbook(ZECOM_FILE, read_only=True, data_only=True)
ws_z = wb_z['MY']

zecom_records = []
for row in ws_z.iter_rows(min_row=5, values_only=True):
    style = row[ZECOM_COLS['style']] if len(row) > ZECOM_COLS['style'] else None
    if not style:
        continue
    def get(key):
        idx = ZECOM_COLS.get(key)
        return row[idx] if idx is not None and len(row) > idx else None
    zecom_records.append({
        'ALU_NO'       : str(style).strip(),
        'Launch_Date'  : get('launch_date'),
        'Status_Lazada': get('status_laz'),
        'Price'        : get('price'),         # AU
        'Special_Price': get('special_price'), # AV
        'Disc_Pct'     : get('disc_pct'),      # AW
        'Exclusion'    : get('exclusion'),     # AX
    })
wb_z.close()

zecom_df = pd.DataFrame(zecom_records).drop_duplicates(subset='ALU_NO')
print(f"  ✓ {len(zecom_df):,} styles loaded")

excl_counts = zecom_df['Exclusion'].value_counts()
print(f"  Exclusion values found:")
for val, cnt in excl_counts.items():
    print(f"    {cnt:>6,}x  {val}")

main_df = price_df.merge(zecom_df, on='ALU_NO', how='left')
print(f"  ✓ Merged: {len(main_df):,} rows")


