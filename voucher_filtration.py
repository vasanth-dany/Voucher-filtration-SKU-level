wb = xlsxwriter.Workbook(OUTPUT_FILE, {'strings_to_numbers': False})

# ── Build formats ─────────────────────────────────────────────
S = STYLING
base = {'font_name': 'Arial', 'font_size': 9, 'valign': 'vcenter', 'border': 1, 'border_color': '#D1D5DB'}

def mkfmt(props):
    return wb.add_format({**base, **props})

FMT = {
    'header'   : mkfmt({'bold': True, 'bg_color': S['header_bg'], 'font_color': '#FFFFFF', 'text_wrap': True, 'align': 'center'}),
    'data'     : mkfmt({'bg_color': '#FFFFFF'}),
    'data_alt' : mkfmt({'bg_color': '#F8FAFC'}),
    'eligible' : mkfmt({'bg_color': S['eligible_bg'],  'font_color': S['eligible_font'],  'bold': True}),
    'flagged'  : mkfmt({'bg_color': S['flagged_bg'],   'font_color': S['flagged_font'],   'bold': True}),
    'amber'    : mkfmt({'bg_color': S['am_excl_bg'],   'font_color': S['am_excl_font'],   'bold': True}),
    'mismatch' : mkfmt({'bg_color': S['mismatch_bg'],  'font_color': S['mismatch_font']}),
    'match'    : mkfmt({'bg_color': S['match_bg'],     'font_color': S['match_font']}),
}

# Per-campaign YES formats
CAMP_FMTS = {}
for camp in CAMPAIGNS:
    CAMP_FMTS[camp['output_col']] = mkfmt({
        'bg_color': camp['cell_color'], 'font_color': camp['font_color'],
        'bold': True, 'align': 'center'
    })

COL_WIDTHS = {
    'Product_ID': 14, 'Product_Name': 32, 'SellerSKU': 18, 'ALU_NO': 14,
    'Status_Active': 11, 'Quantity': 10, 'Price': 12, 'Special_Price': 14,
    'Disc_Pct': 10, 'Live_Date': 14, 'Status_BAU': 12, 'Status_Lazada': 13,
    'Price_vs_SpecialPrice': 18, 'Exclusion': 30, 'AM_Exclusion': 14, 'Eligibility': 30,
}

def write_sheet(sheet_name, df, tab_color='#1E293B'):
    ws = wb.add_worksheet(sheet_name[:31])  # Excel max 31 chars
    ws.set_tab_color(tab_color)
    ws.freeze_panes(1, 0)
    ws.autofilter(0, 0, len(df), len(OUT_COLS) - 1)
    ws.set_row(0, 32)

    for ci, col in enumerate(OUT_COLS):
        ws.write(0, ci, col, FMT['header'])
        ws.set_column(ci, ci, COL_WIDTHS.get(col, 18))

    for ri, (_, row) in enumerate(df.iterrows(), 1):
        alt = ri % 2 == 0
        base_f = FMT['data_alt'] if alt else FMT['data']
        for ci, col in enumerate(OUT_COLS):
            val = row[col]
            if val is None or (isinstance(val, float) and pd.isna(val)):
                val = ''
            elif isinstance(val, (datetime, date)):
                val = str(val)[:10]

            if col == 'Eligibility':
                fmt = FMT['eligible'] if val == 'ELIGIBLE' else FMT['flagged']
            elif col == 'AM_Exclusion' and val == 'EXCLUDE':
                fmt = FMT['amber']
            elif col == 'Price_vs_SpecialPrice':
                fmt = FMT['match'] if val == 'MATCH' else (FMT['mismatch'] if val == 'MISMATCH' else base_f)
            elif col in CAMP_FMTS and val == 'YES':
                fmt = CAMP_FMTS[col]
            else:
                fmt = base_f

            ws.write(ri, ci, val, fmt)

# ── All SKUs sheet ────────────────────────────────────────────
