# STEP 4: Load BAU Voucher File (optional)
# ============================================================
main_df['Live_Date']  = None
main_df['Status_BAU'] = None

if BAU_FILE and os.path.exists(BAU_FILE):
    print("\n▶ STEP 4: Loading BAU Voucher file...")
    try:
        bau_raw = pd.read_excel(BAU_FILE, sheet_name='template', header=0)
        bau_df  = bau_raw.iloc[3:].copy()
        bau_df.columns = bau_raw.columns
        bau_df = bau_df.drop_duplicates(subset='SellerSKU')
        bau_df['SellerSKU'] = bau_df['SellerSKU'].astype(str).str.strip()
        live_col   = next((c for c in bau_df.columns if 'live' in str(c).lower()), None)
        status_col = next((c for c in bau_df.columns if str(c).strip().lower() == 'status'), None)
        cols = ['SellerSKU'] + ([live_col] if live_col else []) + ([status_col] if status_col else [])
        bau_sub = bau_df[cols].copy()
        if live_col:   bau_sub.rename(columns={live_col: 'Live_Date'}, inplace=True)
        if status_col: bau_sub.rename(columns={status_col: 'Status_BAU'}, inplace=True)
        main_df = main_df.merge(bau_sub, on='SellerSKU', how='left', suffixes=('', '_bau'))
        for col in ['Live_Date', 'Status_BAU']:
            if f'{col}_bau' in main_df.columns:
                main_df[col] = main_df[f'{col}_bau'].combine_first(main_df[col])
                main_df.drop(columns=[f'{col}_bau'], inplace=True)
        print(f"  ✓ BAU merged: {len(main_df):,} rows")
    except Exception as e:
        print(f"  WARNING: BAU file error (skipping) — {e}")
else:
    print("\n▶ STEP 4: BAU file not provided — Live_Date / Status_BAU will be blank")


# ============================================================
# STEP 5: AM Exclusion Flag
# ============================================================
am_excl_set = set()
if AM_EXCL_FILE and os.path.exists(AM_EXCL_FILE):
    print("\n▶ STEP 5: Loading AM Exclusion file...")
    am_df = pd.read_excel(AM_EXCL_FILE)
    am_excl_set = set(am_df.iloc[:, 0].dropna().astype(str).str.strip())
    print(f"  ✓ {len(am_excl_set):,} excluded ALU_NOs loaded")
else:
    print("\n▶ STEP 5: AM Exclusion file not provided — AM_Exclusion column will be blank")

main_df['AM_Exclusion'] = main_df['ALU_NO'].apply(
    lambda x: 'EXCLUDE' if pd.notna(x) and str(x).strip() in am_excl_set else ''
)


# ============================================================
# STEP 6: Eligibility Flags
# ============================================================
print("\n▶ STEP 6: Calculating eligibility...")

def check_eligibility(row):
    reasons = []

    # Status Lazada (zeCOM V col)
    if PRE_FILTER_RULES.get('status_lazada_must_be_yes'):
        sl = row.get('Status_Lazada')
        if pd.notna(sl) and str(sl).strip().upper() != 'YES':
            reasons.append('Status Lazada ≠ YES')

    # Status BAU (from BAU file)
    if PRE_FILTER_RULES.get('status_bau_must_be_yes'):
        sb = row.get('Status_BAU')
        if pd.notna(sb) and str(sb).strip().upper() != 'YES':
            reasons.append('Status BAU ≠ YES')

    # Future Live Date (from BAU file)
    if PRE_FILTER_RULES.get('future_live_date'):
        ld = row.get('Live_Date')
        if pd.notna(ld):
            ld_date = ld.date() if isinstance(ld, datetime) else ld
            if isinstance(ld_date, date) and ld_date > TODAY:
                reasons.append('Future Live Date')

    # Price / Special Price threshold
    if PRE_FILTER_RULES.get('min_price_threshold'):
        try:
            pv  = float(row['Price'])         if pd.notna(row.get('Price'))         else None
            spv = float(row['Special_Price'])  if pd.notna(row.get('Special_Price')) else None
            if (pv is not None and pv < MIN_PRICE_THRESHOLD) or \
               (spv is not None and spv < MIN_PRICE_THRESHOLD):
                reasons.append(f'Price or Special Price < {MIN_PRICE_THRESHOLD}')
        except:
            pass

    return 'ELIGIBLE' if not reasons else ' | '.join(reasons)

main_df['Eligibility'] = main_df.apply(check_eligibility, axis=1)
elig_count = (main_df['Eligibility'] == 'ELIGIBLE').sum()
print(f"  ✓ ELIGIBLE : {elig_count:,}")
print(f"  ✗ Flagged  : {len(main_df) - elig_count:,}")


# ============================================================
# STEP 7: Price vs Special Price Check
# ============================================================
def price_check(row):
    try:
        p  = row.get('Price')
        sp = row.get('Special_Price')
        if pd.isna(p) or pd.isna(sp): return 'NO DATA'
        return 'MATCH' if float(p) == float(sp) else 'MISMATCH'
    except:
        return 'NO DATA'

main_df['Price_vs_SpecialPrice'] = main_df.apply(price_check, axis=1)


# ============================================================
# STEP 8: Apply Campaign Rules (from config.py)
# ============================================================
print("\n▶ STEP 8: Applying campaign rules...")

def matches_campaign(excl_val, campaign):
    e  = str(excl_val).strip() if pd.notna(excl_val) else ''
    el = e.lower()
    mt = campaign['match_type']
    mv = [v.lower() for v in campaign['match_values']]
    ex = [v.lower() for v in campaign.get('excludes', [])]

    # Check match
    if mt == 'contains':
        matched = any(m in el for m in mv)
    else:  # exact
        matched = el in mv

    if not matched:
        return False

    # Check excludes
    if any(x in el for x in ex):
        return False

    return True

for camp in CAMPAIGNS:
    col = camp['output_col']
    main_df[col] = main_df.apply(
        lambda row: 'YES'
        if (row['Eligibility'] == 'ELIGIBLE'
            and row['AM_Exclusion'] != 'EXCLUDE'
            and matches_campaign(row.get('Exclusion'), camp))
        else '',
        axis=1
    )
    count = (main_df[col] == 'YES').sum()
    print(f"  {camp['name']}: {count:,} SKUs")


